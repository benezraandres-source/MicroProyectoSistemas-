"""Generate a deterministic offline cache for the actual Flutter web output."""
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'flutter_application_1' / 'build' / 'web'
required = ['index.html', 'main.dart.js', 'flutter_bootstrap.js', 'manifest.json', 'pwa.js', 'canvaskit/canvaskit.wasm']
for name in required:
    if not (root / name).is_file():
        raise SystemExit(f'Missing web resource: {name}')
resources = sorted(p.relative_to(root).as_posix() for p in root.rglob('*')
    if p.is_file() and p.name not in {'sw.js', 'flutter_service_worker.js', 'version.json', '.nojekyll'}
    and not p.name.endswith('.map'))
digest = hashlib.sha256()
for name in resources:
    digest.update(name.encode())
    digest.update((root / name).read_bytes())
version = digest.hexdigest()[:20]
worker = """// Generated by scripts/prepare_pwa.py. Scope is confined to this app.
const SCOPE = new URL('./', self.location.href);
const PREFIX = 'puzzle-offline-' + SCOPE.pathname + ':';
const CACHE = PREFIX + '__VERSION__';
const RESOURCES = __RESOURCES__;
self.addEventListener('install', event => event.waitUntil((async () => {
  const cache = await caches.open(CACHE);
  await cache.addAll(RESOURCES.map(path => new Request(new URL(path, SCOPE), {cache: 'reload'})));
  await self.skipWaiting();
})()));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const name of await caches.keys()) {
    if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
  }
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== SCOPE.origin || !url.pathname.startsWith(SCOPE.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    if (event.request.mode === 'navigate') {
      // Cache-first keeps the shell and compiled app on the same build version.
      return (await cache.match(new URL('index.html', SCOPE))) || fetch(event.request);
    }
    return (await cache.match(event.request, {ignoreSearch: true})) || fetch(event.request);
  })());
});
"""
(root / 'sw.js').write_text(worker.replace('__VERSION__', version).replace('__RESOURCES__', json.dumps(resources)), encoding='utf-8')
(root / '.nojekyll').touch()
print(f'Offline cache {version}: {len(resources)} local resources.')
